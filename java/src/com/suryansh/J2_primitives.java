package com.suryansh;

public class J2_primitives {
    public static void main(String[] args) {
        int rollno = 64;
        //primitives are data types which cannot be break further
        char letter = 'S';
        float marks = 5.6f;
        double largeNumberDecimal = 4545445.554;
        long largerInteger = 653752989842L;
        boolean check = true;

        System.out.println(rollno);
        System.out.println(letter);
        System.out.println(marks);
        System.out.println(largeNumberDecimal);
        System.out.println(largerInteger);
        System.out.println(check);
    }
}
